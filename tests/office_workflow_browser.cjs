// Real local browser validation of direct Office-style operations, no remote models.
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const {chromium}=require(process.env.PPT_PLAYWRIGHT_MODULE||'playwright-core');
const url=process.env.PPT_STUDIO_TEST_URL,output=process.env.PPT_BROWSER_OUTPUT||'/tmp/weppt-office';
(async()=>{
 await fs.mkdir(output,{recursive:true});
 const browser=await chromium.launch({headless:true,executablePath:process.env.WEPPT_CHROMIUM});
 const page=await browser.newPage({viewport:{width:1440,height:950},baseURL:new URL(url).origin});
 page.setDefaultTimeout(15000);const errors=[];
 page.on('pageerror',e=>{errors.push(e.message);console.error('PAGE ERROR',e.message)});
 const headers=()=>({Origin:new URL(url).origin,'X-WePPT-Project':new URL(page.url()).searchParams.get('project')||'demo'});
 const state=()=>page.request.get('/api/state',{headers:headers()}).then(r=>r.json());
 const scenes=async()=>{const s=await state();return Promise.all(s.slides.map(p=>page.request.get('/api/scene?slide='+p.id,{headers:headers()}).then(r=>r.json()).then(r=>r.scene)))};
 try{
  await page.goto(url);
  const created=await page.request.post('/api/projects',{headers:{Origin:new URL(url).origin},data:{title:'Office workflow test'}}).then(r=>r.json());
  await page.request.post('/api/demo',{headers:{Origin:new URL(url).origin,'X-WePPT-Project':created.projectId},data:{}});
  await page.goto(new URL('/?project='+created.projectId,url).href);
  await page.screenshot({path:`${output}/office-initial.png`,fullPage:true});
  await page.locator('.page-frame.active').waitFor();
  const initial=await state();let ids=initial.slides.map(p=>p.id);
  await page.locator('#slide-add').click();
  await page.waitForFunction(n=>document.querySelector('#slide-count').textContent===`${n} 页`,ids.length+1);
  const inserted=await state(),sid=inserted.selectedSlideId,index=ids.indexOf(initial.selectedSlideId);
  assert.deepEqual(inserted.slides.map(p=>p.id),[...ids.slice(0,index+1),sid,...ids.slice(index+1)]);
  await page.locator('#slide-copy').click();
  await page.waitForFunction(n=>document.querySelector('#slide-count').textContent===`${n} 页`,ids.length+2);
  const copied=await state();assert.notEqual(copied.selectedSlideId,sid);
  await page.locator('#slide-remove').click();
  await page.waitForFunction(n=>document.querySelector('#slide-count').textContent===`${n} 页`,ids.length+1);
  await Promise.all([page.waitForResponse(r=>r.url().includes('/api/document')&&r.request().method()==='POST'&&r.request().postDataJSON().action==='undo'),page.locator('#undo-button').click()]);
  await page.waitForFunction(n=>document.querySelector('#slide-count').textContent===`${n} 页`,ids.length+2);
  assert.equal((await state()).selectedSlideId,copied.selectedSlideId);
  console.log('PASS direct add at selection, duplicate, delete and document undo');
  await page.locator('#slide-up').click();
  await page.waitForFunction(async sid=>{let s=await(await fetch('/api/state?project='+new URL(location.href).searchParams.get('project'))).json();return s.slides.findIndex(p=>p.id===s.selectedSlideId)<s.slides.findIndex(p=>p.id===sid)},sid);
  await Promise.all([page.waitForResponse(r=>r.url().includes('/api/document')&&r.request().method()==='POST'&&r.request().postDataJSON().action==='undo'),page.locator('#undo-button').click()]);
  console.log('PASS move and restore page order');
  await page.locator('#message-input').fill('留给下一次的草稿');await page.reload();
  await page.waitForFunction(()=>document.querySelector('#message-input').value==='留给下一次的草稿');
  await page.locator('#message-input').fill('');
  console.log('PASS composer draft survives reload');
  const originalScenes=await scenes();
  await page.locator('#ribbon-design-tab').click();
  await page.locator('#ribbon-palette').click();
  await page.locator('.palette-preset').filter({hasText:'沉稳墨绿'}).click();
  await page.locator('#palette-apply-deck').click();
  await page.locator('#palette-dialog').waitFor({state:'hidden'});
  assert.notDeepEqual(await scenes(),originalScenes);
  await page.locator('#ribbon-home-tab').click();
  await Promise.all([page.waitForResponse(r=>r.url().includes('/api/document')&&r.request().method()==='POST'&&r.request().postDataJSON().action==='undo'),page.locator('#undo-button').click()]);
  await page.waitForFunction(async()=>{let s=await(await fetch('/api/state?project='+new URL(location.href).searchParams.get('project'))).json();return !s.documentHistory.canUndo});
  assert.deepEqual(await scenes(),originalScenes);
  console.log('PASS whole-deck palette changes and single-click restoration');
  await page.locator('#ribbon-design-tab').click();
  await page.locator('#ribbon-style').click();
  await page.locator('#style-dialog').waitFor({state:'visible'});
  await page.evaluate(()=>{
    const canvas=document.createElement('canvas');canvas.width=128;canvas.height=72;
    const ctx=canvas.getContext('2d');ctx.fillStyle='#224466';ctx.fillRect(0,0,128,72);
    const raw=Uint8Array.from(atob(canvas.toDataURL('image/png').split(',')[1]),c=>c.charCodeAt(0));
    const data=new DataTransfer();data.items.add(new File([raw],'clipboard.png',{type:'image/png'}));
    document.dispatchEvent(new ClipboardEvent('paste',{clipboardData:data,bubbles:true,cancelable:true}));
  });
  await page.locator('#style-error').waitFor({state:'visible'});
  assert.match(await page.locator('#style-error').textContent(),/模型|图片|看图/);
  assert.equal(await page.locator('#style-list .style-item').count(),1);
  await page.screenshot({path:`${output}/reference-paste.png`,fullPage:true});
  await page.locator('#style-close').click();
  console.log('PASS one reference image pasted and retained; missing vision reported honestly');
  await page.locator('#ribbon-home-tab').click();
  await page.screenshot({path:`${output}/office-desktop.png`,fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-mobile-tab="preview"]').click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:`${output}/office-mobile.png`,fullPage:true});
  await page.setViewportSize({width:1440,height:950});
  const PptxGenJS=require('pptxgenjs'),pptx=new PptxGenJS();pptx.layout='LAYOUT_WIDE';
  for(let i=1;i<=2;i++){const slide=pptx.addSlide();slide.addText('原稿第'+i+'页',{x:1,y:1,w:10,h:1,fontSize:32,color:'243247',fontFace:'Arial',margin:0});slide.addNotes('原始备注');}
  const source=Buffer.from(await pptx.write({outputType:'nodebuffer'}));
  await page.locator('#presentation-input').setInputFiles({name:'test-original.pptx',mimeType:'application/vnd.openxmlformats-officedocument.presentationml.presentation',buffer:source});
  await page.waitForURL(u=>u.searchParams.get('project')!==created.projectId);
  await page.locator('.page-frame.active').waitFor();
  const imported=await state();assert.equal(imported.slides.length,2);
  const download=await page.request.get('/api/source',{headers:headers()});assert.deepEqual(await download.body(),source);
  assert.equal(imported.importSource.filename,'test-original.pptx');
  await page.screenshot({path:`${output}/opened-pptx.png`,fullPage:true});
  console.log('PASS existing PPTX opens all pages in a new project and original downloads byte-for-byte');
  assert.deepEqual(errors,[]);
 }catch(e){await page.screenshot({path:`${output}/office-failure.png`,fullPage:true});console.log('page',await page.locator('body').innerText());throw e;}
 finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
