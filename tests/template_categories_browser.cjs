const assert=require('node:assert/strict');
const {chromium}=require(process.env.PPT_PLAYWRIGHT_MODULE || 'playwright');
const url=process.env.PPT_STUDIO_TEST_URL;
if(!url)throw Error('Set PPT_STUDIO_TEST_URL. This check only reads and previews.');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true,args:['--no-proxy-server']});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[],writes=[];
  page.setDefaultTimeout(30000);
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.method()==='POST' && /\/api\/(?:jobs|templates\/select|edit|messages)/.test(r.url()))writes.push(r.url());});
  await page.goto(url,{waitUntil:'domcontentloaded'});
  await page.locator('#ribbon-design-tab').click();await page.locator('#ribbon-styles').click();
  await page.waitForFunction(()=>document.querySelectorAll('#template-roles button').length===14);
  const category=id=>page.locator(`#template-roles [data-category="${id}"]`);
  await page.locator('[data-template-filter=reference]').click();
  assert.match(await category('all').innerText(),/44/);
  const counts=await page.locator('#template-roles button').allTextContents();
  assert.equal(counts.slice(1).reduce((s,x)=>s+Number(x.split('·')[1]),0),44);
  assert(!counts.some(x=>x.includes('正文')));
  await category('people').click();
  assert.equal(await page.locator('#template-grid .template-card').count(),2);
  assert.match(await page.locator('#template-grid').innerText(),/单人物简介/);
  await category('data').click();
  assert.equal(await page.locator('#template-grid .template-card').count(),2);
  assert.match(await page.locator('#template-grid').innerText(),/主图与三组图例说明/);
  await page.waitForFunction(()=>[...document.querySelectorAll('#template-grid img')].every(i=>i.complete&&i.naturalWidth>0),null,{timeout:90000});
  const out=process.env.PPT_BROWSER_OUTPUT || '/tmp/weppt-categories';
  await require('node:fs/promises').mkdir(out,{recursive:true});
  await page.screenshot({path:out+'/categories.png',fullPage:true});
  await page.locator('[data-template-filter=all]').click();
  assert.match(await category('all').innerText(),/78/);
  await category('all').click();
  await page.locator('#template-position').selectOption('ending');
  assert.equal(await page.locator('#template-grid .template-card').count(),1);
  await page.locator('[data-template-filter=reference]').click();
  assert.equal(await page.locator('#template-grid .template-card').count(),3);
  await page.locator('#template-position').selectOption('all');
  await category('people').click();
  await page.locator('#template-search').fill('单人物');
  assert.equal(await page.locator('#template-grid .template-card').count(),1);
  await page.locator('#template-search').fill('');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:out+'/categories-mobile.png',fullPage:true});
  assert(await page.locator('#templates-panel').evaluate(e=>e.scrollWidth<=e.clientWidth+1));
  assert.deepEqual(errors,[]);assert.deepEqual(writes,[]);
  console.log('PASS purpose categories, source counts, original metadata, position filter, search, mobile, no model/edit requests, no JS errors');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
